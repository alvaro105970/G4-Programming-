print("Welcome to the simple calculator This program is a simple four function calculator. It takes two numbers from the user to perform addition, subtraction, multiplication, or division.")
n1=int(input("enter your first number :"))
n2=int(input("enter your second number :"))
print(f"{n1} + {n2} = {n1+n2}")
print(f"{n1} - {n2} = {n1-n2}")
print(f"{n1} * {n2} = {n1*n2}")
print(f"{n1} / {n2} = {n1/n2}")
print("Thank you for using Simple Calculator!")